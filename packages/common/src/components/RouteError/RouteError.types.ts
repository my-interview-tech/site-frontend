export type RouteErrorProps = {
  /**
   * Заголовок.
   * @default 'Не удалось загрузить данные'
   */
  title?: string

  /**
   * Пояснение под заголовком.
   * @default 'Сервер временно недоступен. Попробуйте повторить запрос или обновите страницу.'
   */
  caption?: string

  /**
   * Карточка внутри страницы, без высоты на весь экран.
   * @default false
   */
  compact?: boolean

  /**
   * Адрес кнопки «На главную» и крестика без `onClose`.
   * @default '/'
   */
  homeHref?: string

  /**
   * Закрыть карточку. Без него крестик ведёт на `homeHref`.
   */
  onClose?: () => void

  /**
   * Вернуться на предыдущую страницу. Кнопка «Назад» есть только с этим колбэком.
   */
  onBack?: () => void

  /**
   * Повторить запрос. Без него страница перезагружается.
   */
  onRetry?: () => void

  /**
   * Карточка поверх страницы, фон закрывает экран.
   * @default false
   */
  overlay?: boolean

  /**
   * Показывать кнопку «Повторить».
   * @default true
   */
  retry?: boolean
}
